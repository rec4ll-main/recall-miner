func TestLoadOrGenerate_AutoGenCreatesAndPersists(t *testing.T) {
	dir := t.TempDir()
	certFile := filepath.Join(dir, "tls", "cert.pem")
	keyFile := filepath.Join(dir, "tls", "key.pem")
	cert, err := LoadOrGenerate(certFile, keyFile, "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY", nil, true)
	if err != nil {
		t.Fatalf("LoadOrGenerate auto-gen: %v", err)
	}
	if len(cert.Certificate) == 0 {
		t.Fatal("expected certificate DER")
	}
	if _, err := os.Stat(certFile); err != nil {
		t.Fatalf("cert file not persisted: %v", err)
	}
	if fi, err := os.Stat(keyFile); err != nil {
		t.Fatalf("key file not persisted: %v", err)
	} else if fi.Mode().Perm() != 0o600 {
		t.Fatalf("key file mode = %v, want 0600", fi.Mode().Perm())
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		t.Fatal(err)
	}
	// The certificate names no hotkey: a TLS handshake must not identify the miner.
	if got := parsed.Subject.CommonName; got != "" {
		t.Fatalf("CN = %q, want none", got)
	}
	for _, n := range parsed.DNSNames {
		if n == "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY" {
			t.Fatal("the hotkey must not be a DNS name")
		}
	}
	if parsed.NotAfter.Sub(parsed.NotBefore) < 825*24*time.Hour {
		t.Fatalf("cert lifetime too short: %v", parsed.NotAfter.Sub(parsed.NotBefore))
	}
}

func TestLoadOrGenerate_NoRegenAndStablePin(t *testing.T) {
	dir := t.TempDir()
	certFile := filepath.Join(dir, "cert.pem")
	keyFile := filepath.Join(dir, "key.pem")
	hotkey := "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY"

	cert1, err := LoadOrGenerate(certFile, keyFile, hotkey, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	pin1, err := SPKIPin(cert1)
	if err != nil {
		t.Fatal(err)
	}
	beforeCert, _ := os.ReadFile(certFile)
	beforeKey, _ := os.ReadFile(keyFile)
	time.Sleep(10 * time.Millisecond)

	cert2, err := LoadOrGenerate(certFile, keyFile, hotkey, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	pin2, err := SPKIPin(cert2)
	if err != nil {
		t.Fatal(err)
	}
	if pin1 != pin2 {
		t.Fatalf("SPKI pin changed across restarts: %q vs %q", pin1, pin2)
	}
	afterCert, _ := os.ReadFile(certFile)
	afterKey, _ := os.ReadFile(keyFile)
	if string(beforeCert) != string(afterCert) || string(beforeKey) != string(afterKey) {
		t.Fatal("certificate/key were regenerated on an existing valid file")
	}
}

func TestSPKIPin_GoldenDerivation(t *testing.T) {
	dir := t.TempDir()
	certFile := filepath.Join(dir, "cert.pem")
	keyFile := filepath.Join(dir, "key.pem")
	cert, err := LoadOrGenerate(certFile, keyFile, "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY", nil, true)
	if err != nil {
		t.Fatal(err)
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(parsed.RawSubjectPublicKeyInfo)
	want := base64.StdEncoding.EncodeToString(sum[:])
	pin, err := SPKIPin(cert)
	if err != nil {
		t.Fatal(err)
	}
	if pin != want {
		t.Fatalf("SPKI pin = %q, want base64(sha256(RawSubjectPublicKeyInfo)) = %q", pin, want)
	}
}

