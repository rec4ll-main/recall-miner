func TestLoadOrGenerate_SANHostsPopulated(t *testing.T) {
	dir := t.TempDir()
	certFile := filepath.Join(dir, "cert.pem")
	keyFile := filepath.Join(dir, "key.pem")
	hotkey := "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY"
	cert, err := LoadOrGenerate(certFile, keyFile, hotkey, []string{"192.0.2.43:8001"}, true)
	if err != nil {
		t.Fatal(err)
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		t.Fatal(err)
	}
	foundIP := false
	for _, ip := range parsed.IPAddresses {
		if ip.String() == "192.0.2.43" {
			foundIP = true
		}
	}
	if !foundIP {
		t.Fatalf("expected 192.0.2.43 in cert IP SANs, got %v", parsed.IPAddresses)
	}
}

// Certificates generated by earlier versions name the hotkey. On load they are reissued
// with the same key, so the pin the API recorded does not change, and the key file is
// left as it is.
func TestLoadOrGenerate_ReissuesOldHotkeyCertWithSameKey(t *testing.T) {
	const hotkey = "5GrwvaEF5zXb26Fz9rcQpDWS57CtERHpNehXCPcNoHGKutQY"
	dir := t.TempDir()
	certFile, keyFile := filepath.Join(dir, "tls.crt"), filepath.Join(dir, "tls.key")
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	now := time.Now()
	old := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: hotkey},
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.Add(900 * 24 * time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		DNSNames:     []string{hotkey, "miner", "miner-m0", "localhost"},
		IPAddresses:  []net.IP{net.ParseIP("127.0.0.1"), net.ParseIP("192.0.2.44")},
	}
	der, err := x509.CreateCertificate(rand.Reader, old, old, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	if err := persist(certFile, keyFile, der, key); err != nil {
		t.Fatal(err)
	}
	before, err := load(certFile, keyFile)
	if err != nil {
		t.Fatal(err)
	}
	pinBefore, _ := SPKIPin(before)
	keyBefore, _ := os.ReadFile(keyFile)

	got, err := LoadOrGenerate(certFile, keyFile, hotkey, []string{"203.0.113.5:8001"}, true)
	if err != nil {
		t.Fatal(err)
	}
	if namesHotkey(got, hotkey) {
		t.Fatal("the reissued certificate still names the hotkey")
	}
	if pin, _ := SPKIPin(got); pin != pinBefore {
		t.Fatalf("pin changed: %s -> %s", pinBefore, pin)
	}
	// Every name and address a client may connect by is kept, and the endpoint host added.
	reissued, err := x509.ParseCertificate(got.Certificate[0])
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"miner", "miner-m0", "localhost", "127.0.0.1", "192.0.2.44", "203.0.113.5"} {
		if err := reissued.VerifyHostname(name); err != nil {
			t.Errorf("the reissued certificate must still cover %s: %v", name, err)
		}
	}
	if keyAfter, _ := os.ReadFile(keyFile); !bytes.Equal(keyAfter, keyBefore) {
		t.Fatal("the key file must not be rewritten")
	}
	again, err := LoadOrGenerate(certFile, keyFile, hotkey, nil, true)
	if err != nil || !bytes.Equal(again.Certificate[0], got.Certificate[0]) {
		t.Fatalf("a reissued certificate is loaded as it is afterwards: %v", err)
	}
	// An operator-supplied certificate (auto-generation off) is never rewritten.
	if err := persist(certFile, keyFile, der, key); err != nil {
		t.Fatal(err)
	}
	kept, err := LoadOrGenerate(certFile, keyFile, hotkey, nil, false)
	if err != nil || !namesHotkey(kept, hotkey) {
		t.Fatalf("with TLS_AUTO_GENERATE=false the certificate is used as supplied: %v", err)
	}
}
