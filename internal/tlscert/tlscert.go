// Package tlscert loads or auto-generates the miner's self-signed TLS
// certificate and derives its SPKI pin. The TLS identity is the pin: the
// sha256 of the certificate's SubjectPublicKeyInfo, which the Recall API records
// at registration (signed by the miner hotkey) and enforces on later connections.
// The certificate itself names no hotkey, so a TLS handshake does not tell a
// stranger which miner it reached.
package tlscert

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/base64"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"time"
)

// minCertLifetime is the shortest acceptable certificate validity window
// (825 days). Certificates are regenerated when the on-disk certificate is
// missing, unparseable, or has expired; otherwise the existing files are
// reused so the SPKI pin stays stable across restarts.
const minCertLifetime = 825 * 24 * time.Hour

// LoadOrGenerate returns the miner's TLS certificate, loading it from
// certFile/keyFile when both exist and parse, or generating a fresh
// self-signed certificate and persisting it when autoGenerate is true and the
// files are missing or unusable. sanHosts are the public endpoint host:port
// values the certificate should be valid for (they are turned into IP or DNS
// SANs at generation time; they do not affect loading). When autoGenerate is
// false and the files are missing or unparseable, it returns an error so the
// caller fails startup.
func LoadOrGenerate(certFile, keyFile, hotkey string, sanHosts []string, autoGenerate bool) (tls.Certificate, error) {
	if certFile == "" || keyFile == "" {
		return tls.Certificate{}, errors.New("TLS_CERT_FILE and TLS_KEY_FILE must both be set when TLS is enabled")
	}
	if loaded, err := load(certFile, keyFile); err == nil {
		if autoGenerate && namesHotkey(loaded, hotkey) {
			// Certificates generated before this change carry the hotkey as their name.
			// Reissue with the SAME key: the pin (and the API's record of it) is unchanged.
			if key, ok := loaded.PrivateKey.(*ecdsa.PrivateKey); ok {
				if reissued, err := reissueWithoutHotkey(certFile, keyFile, key, loaded, hotkey, sanHosts); err == nil {
					return reissued, nil
				}
			}
		}
		return loaded, nil
	}
	if !autoGenerate {
		return tls.Certificate{}, fmt.Errorf("TLS_AUTO_GENERATE=false but certificate/key are missing or unparseable (%s, %s)", certFile, keyFile)
	}
	generated, err := generateAndPersist(certFile, keyFile, hotkey, sanHosts)
	if err != nil {
		return tls.Certificate{}, err
	}
	return generated, nil
}

// SPKIPin computes the tls_spki_sha256 pin: base64(sha256(SPKI bytes)) of the
// certificate's RawSubjectPublicKeyInfo. The validator derives the identical
// value from the presented certificate, so the two must match byte-for-byte.
func SPKIPin(cert tls.Certificate) (string, error) {
	if len(cert.Certificate) == 0 {
		return "", errors.New("certificate has no DER bytes")
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		return "", fmt.Errorf("parse certificate for SPKI pin: %w", err)
	}
	sum := sha256.Sum256(parsed.RawSubjectPublicKeyInfo)
	return base64.StdEncoding.EncodeToString(sum[:]), nil
}

func load(certFile, keyFile string) (tls.Certificate, error) {
	cert, err := tls.LoadX509KeyPair(certFile, keyFile)
	if err != nil {
		return tls.Certificate{}, err
	}
	if len(cert.Certificate) == 0 {
		return tls.Certificate{}, errors.New("loaded certificate is empty")
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		return tls.Certificate{}, err
	}
	if time.Now().After(parsed.NotAfter) {
		return tls.Certificate{}, fmt.Errorf("loaded certificate expired at %s", parsed.NotAfter)
	}
	return cert, nil
}

// namesHotkey reports whether the certificate carries the hotkey as its common name or
// a DNS name (certificates generated by earlier versions did).
func namesHotkey(cert tls.Certificate, hotkey string) bool {
	if hotkey == "" || len(cert.Certificate) == 0 {
		return false
	}
	parsed, err := x509.ParseCertificate(cert.Certificate[0])
	if err != nil {
		return false
	}
	if parsed.Subject.CommonName == hotkey {
		return true
	}
	for _, n := range parsed.DNSNames {
		if n == hotkey {
			return true
		}
	}
	return false
}

// reissueWithoutHotkey writes a new certificate for the existing key (the key file is
// not touched) and loads it. It keeps every DNS name and IP address of the old
// certificate except the hotkey, and adds the current endpoint hosts: sidecars and other
// clients may connect by a name the old certificate carried (localhost, a container name,
// a LAN address), and must keep verifying after the reissue.
func reissueWithoutHotkey(certFile, keyFile string, key *ecdsa.PrivateKey, old tls.Certificate, hotkey string, sanHosts []string) (tls.Certificate, error) {
	parsed, err := x509.ParseCertificate(old.Certificate[0])
	if err != nil {
		return tls.Certificate{}, err
	}
	keep := make([]string, 0, len(sanHosts)+len(parsed.DNSNames)+len(parsed.IPAddresses))
	keep = append(keep, sanHosts...)
	for _, n := range parsed.DNSNames {
		if n != hotkey {
			keep = append(keep, n)
		}
	}
	for _, ip := range parsed.IPAddresses {
		keep = append(keep, ip.String())
	}
	der, err := createCertificate(key, keep)
	if err != nil {
		return tls.Certificate{}, err
	}
	if err := writeFile(certFile, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
		return tls.Certificate{}, err
	}
	return load(certFile, keyFile)
}

func generateAndPersist(certFile, keyFile, _ string, sanHosts []string) (tls.Certificate, error) {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return tls.Certificate{}, fmt.Errorf("generate ECDSA P-256 key: %w", err)
	}
	der, err := createCertificate(key, sanHosts)
	if err != nil {
		return tls.Certificate{}, err
	}
	if err := persist(certFile, keyFile, der, key); err != nil {
		return tls.Certificate{}, err
	}
	cert, err := load(certFile, keyFile)
	if err != nil {
		return tls.Certificate{}, fmt.Errorf("reload generated certificate: %w", err)
	}
	return cert, nil
}

// createCertificate self-signs a certificate for key, valid for the public endpoint
// hosts. It names no hotkey: the API identifies the miner by the key's pin.
func createCertificate(key *ecdsa.PrivateKey, sanHosts []string) ([]byte, error) {
	now := time.Now()
	template := &x509.Certificate{
		SerialNumber: big.NewInt(now.UnixNano()),
		Subject:      pkix.Name{},
		NotBefore:    now.Add(-1 * time.Hour),
		NotAfter:     now.Add(minCertLifetime),
		KeyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	ipSet := map[string]net.IP{}
	dnsSet := map[string]bool{}
	for _, host := range sanHosts {
		h := hostHost(host)
		if h == "" {
			continue
		}
		if ip := net.ParseIP(h); ip != nil {
			ipSet[h] = ip
		} else {
			dnsSet[h] = true
		}
	}
	for _, ip := range ipSet {
		template.IPAddresses = append(template.IPAddresses, ip)
	}
	for dns := range dnsSet {
		template.DNSNames = append(template.DNSNames, dns)
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		return nil, fmt.Errorf("create self-signed certificate: %w", err)
	}
	return der, nil
}

func hostHost(hostport string) string {
	if h, _, err := net.SplitHostPort(hostport); err == nil {
		return h
	}
	return hostport
}

func persist(certFile, keyFile string, der []byte, key *ecdsa.PrivateKey) error {
	if err := os.MkdirAll(filepath.Dir(certFile), 0o755); err != nil {
		return fmt.Errorf("create cert directory: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(keyFile), 0o700); err != nil {
		return fmt.Errorf("create key directory: %w", err)
	}
	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})
	if err := writeFile(certFile, certPEM, 0o644); err != nil {
		return err
	}
	keyDER, err := x509.MarshalECPrivateKey(key)
	if err != nil {
		return fmt.Errorf("marshal EC private key: %w", err)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDER})
	if err := writeFile(keyFile, keyPEM, 0o600); err != nil {
		return err
	}
	return nil
}

func writeFile(path string, data []byte, mode os.FileMode) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, mode)
	if err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	defer f.Close()
	if _, err := f.Write(data); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	if err := f.Sync(); err != nil {
		return fmt.Errorf("sync %s: %w", path, err)
	}
	return nil
}
